# Написать программу на Python, которая будет проводить сканирование с использованием nmap.
import nmap

nm = nmap.PortScanner()

# Определите целевой IP-адрес для сканирования
IP = "192.168.1.113"

# Определите параметры сканирования:
# -sV: Прощупывайте открытые порты, чтобы определить информацию о службе/версии
# -sC: Запуск сценариев по умолчанию
options = "-sV -sC"

# Выполните сканирование цели, используя заданные параметры
nm.scan(IP, arguments=options)

# Итерация по всем хостам, найденным в ходе сканирования
for host in nm.all_hosts():
    # Выведите IP-адрес хоста и его имя (если доступно).
    print("Host: %s (%s)" % (host, nm[host].hostname()))
    # Выведите состояние хоста (например, 'up' or 'down')
    print("State: %s" % nm[host].state())
    
    # Переберите все протоколы (например, tcp, udp), обнаруженные на хосте.
    for protocol in nm[host].all_protocols():
        # Печать типа протокола
        print("Protocol: %s" % protocol)
        # Получение информации о порте для текущего протокола
        port_info = nm[host][protocol]
        
        # Итерация по каждому порту и его состоянию (например, открыт, закрыт)
        for port, state in port_info.items():
            # Выведите номер порта и его состояние
            print("Port: %s\tState: %s" % (port, state))
            

